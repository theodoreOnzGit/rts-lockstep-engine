/* Differential-test wrapper for the W3D box, sphere and ring prototype
** loaders (upstream commit 0a05454d): BoxLoaderClass::Load_W3D and
** BoxPrototypeClass's constructor, Get_Name and Get_Class_ID (boxrobj.cpp);
** SphereLoaderClass::Load_W3D and SpherePrototypeClass's constructor,
** destructor, Load, Get_Name and Get_Class_ID (sphereobj.cpp); the same for
** rings (ringobj.cpp), all COMPILED from verbatim segments of those files
** that build.rs copies into OUT_DIR, with the real boxrobj.h, sphereobj.h,
** ringobj.h and prim_anim.h (PrimitiveAnimationChannelClass::Load and
** Load_Variables, which do the channel reading) and w3d_file.h.
** differential/shim_w3d/w3d_prelude.h and mesh_prelude.h are
** force-included. Two WWLib/WW3D2 headers are used as copies with `this->`
** added where a template names a member of its dependent base class (MSVC
** found them without; clang rejects them when the template is instantiated,
** as for Vector.H, see build.rs): simplevec.h (SimpleDynVecClass) and
** prim_anim.h (LERPAnimationChannelClass::Evaluate, which is not run here
** but is instantiated with the channels' vtables).
**
** Nothing is transcribed. Stand-ins never reached (they abort): the three
** prototypes' Create, which builds the render object (named by their
** vtables).
**
** Allocation (zero-filled, as the game's allocator) and the file are
** wrap_w3d.cpp's. The log is reproduced by tests/differential_w3d.rs. */
