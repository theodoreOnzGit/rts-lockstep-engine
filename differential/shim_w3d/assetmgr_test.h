/* nullrobj.h, nullrobj.cpp: NullPrototypeClass (transcribed, see above). */
class NullPrototypeClass : public PrototypeClass
{
public:
	NullPrototypeClass(void)
	{
		/* Note that the other members of the definition are uninitialized..
		** (zeros here: static storage) */
		strcpy(Definition.Name, "NULL");
	}
	NullPrototypeClass(const W3dNullObjectStruct &null) { Definition = null; }
	virtual const char *Get_Name(void) const { return Definition.Name; }
	virtual int Get_Class_ID(void) const { return 22; /* RenderObjClass::CLASSID_NULL */ }
	virtual RenderObjClass *Create(void) { ref_assetmgr_note_create(this); return NULL; }
	virtual void DeleteSelf() { delete this; }
	W3dNullObjectStruct Definition;
};

