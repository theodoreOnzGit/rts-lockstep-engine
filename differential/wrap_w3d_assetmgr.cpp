/* A new asset manager: the destructor of the previous one (verbatim: Free,
** Free_Assets), then the library's (game = 0, on-demand loading off) or the
** game's (game = 1: W3DAssetManager, W3DDisplay's two extra loaders and
** Set_WW3D_Load_On_Demand(true)). No files; the language "english"; no
** TheGlobalData unless user_data is given. */
void ref_assetmgr_reset(int game, const char *user_data)
{
	with_manager([&]() {
		delete g_mgr;
		g_mgr = NULL;
		g_files.clear();
		g_language = "english";
		g_has_global_data = user_data != NULL;
		g_user_data = user_data ? user_data : "";
		if (game) {
			g_mgr = new TestW3DAssetManager;
			g_mgr->Register_Prototype_Loader(&ref_loader_emitter);
			g_mgr->Register_Prototype_Loader(&ref_loader_aggregate2);
			g_mgr->Set_WW3D_Load_On_Demand(true);
		} else {
			g_mgr = new WW3DAssetManager;
		}
	});
}

/* A file of TheFileSystem. */
void ref_assetmgr_add_file(const char *path, const char *data, int len)
{
	g_files[normalise(path)] = std::string(data, len);
}

/* One operation on the manager, logged:
**   0 Load_3D_Assets(FileClass &) on the bytes: 'B', the result;
**   1 Load_3D_Assets(name): 'L', the result;
**   2 Create_Render_Obj(name): 'R', whether a prototype was asked to
**     Create, its name and class id;
**   3 Get_HTree(name): 'H', found, its name and Num_Pivots;
**   4 Get_HAnim(name): 'N', found, its name; then Is_Missing(name);
**   5 Render_Obj_Exists(name): 'E', the result;
**   6 Free_Assets(): 'F';
**   7 Remove_Prototype(name): 'X';
**   8 Set_WW3D_Load_On_Demand(arg[0]): 'D';
**   9 the state: 'P' the prototypes in order (name, class id), 'T' the
**     hierarchies in order (name, Num_Pivots), 'A' the animations in
**     HAnimManagerIterator order (name). */
int ref_assetmgr_op(int op, const char *arg, int len, unsigned char *log, int cap, int *log_len)
{
	g_log.clear();
	std::string name(arg, len);
	with_manager([&]() {
		switch (op) {
		case 0: {
			BytesFile f(arg, len);
			put8('B');
			put8(g_mgr->Load_3D_Assets(f));
			break;
		}
		case 1:
			put8('L');
			put8(g_mgr->Load_3D_Assets(name.c_str()));
			break;
		case 2: {
			g_created = NULL;
			put8('R');
			g_mgr->Create_Render_Obj(name.c_str());
			put8(g_created != NULL);
			if (g_created) {
				putStr(g_created->Get_Name());
				put32((uint32_t)g_created->Get_Class_ID());
			}
			break;
		}
		case 3: {
			put8('H');
			HTreeClass *t = g_mgr->Get_HTree(name.c_str());
			put8(t != NULL);
			if (t) {
				putStr(t->Get_Name());
				put32((uint32_t)t->Num_Pivots());
			}
			break;
		}
		case 4: {
			put8('N');
			HAnimClass *a = g_mgr->Get_HAnim(name.c_str());
			put8(a != NULL);
			if (a) {
				putStr(a->Get_Name());
				a->Release_Ref();
			}
			put8(g_mgr->HAnimManager.Is_Missing(name.c_str()));
			break;
		}
		case 5:
			put8('E');
			put8(g_mgr->Render_Obj_Exists(name.c_str()));
			break;
		case 6:
			put8('F');
			g_mgr->Free_Assets();
			break;
		case 7:
			put8('X');
			g_mgr->Remove_Prototype(name.c_str());
			break;
		case 8:
			put8('D');
			g_mgr->Set_WW3D_Load_On_Demand(len > 0 && arg[0] != 0);
			break;
		default: {
			put8('P');
			put32((uint32_t)g_mgr->Prototypes.Count());
			for (int i = 0; i < g_mgr->Prototypes.Count(); ++i) {
				putStr(g_mgr->Prototypes[i]->Get_Name());
				put32((uint32_t)g_mgr->Prototypes[i]->Get_Class_ID());
			}
			put8('T');
			put32((uint32_t)g_mgr->HTreeManager.Num_Trees());
			for (int i = 0; i < g_mgr->HTreeManager.Num_Trees(); ++i) {
				HTreeClass *t = g_mgr->HTreeManager.Get_Tree(i);
				putStr(t->Get_Name());
				put32((uint32_t)t->Num_Pivots());
			}
			put8('A');
			std::vector<std::string> names;
			HAnimManagerIterator it(g_mgr->HAnimManager);
			for (it.First(); !it.Is_Done(); it.Next()) names.push_back(it.Get_Current_Anim()->Get_Name());
			put32((uint32_t)names.size());
			for (size_t i = 0; i < names.size(); ++i) putStr(names[i].c_str());
			break;
		}
		}
	});
	return copy_log(log, cap, log_len);
}

