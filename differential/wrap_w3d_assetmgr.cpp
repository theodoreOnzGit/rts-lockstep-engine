/* The loaders (see the top). */
PrototypeClass *TestLoaderClass::Load_W3D(ChunkLoadClass &cload)
{
	switch (Kind) {
	case K_MESH: {
		/* MeshLoaderClass::Load_W3D: a MeshClass over the loaded model,
		** named by it (PrimitivePrototypeClass, CLASSID_MESH) */
		std::string name;
		if (!ref_w3d_mesh_load_for_assetmgr(cload, name)) return NULL;
		return new TestProtoClass(name.c_str(), 0, NULL);
	}
	case K_COLLECTION: {
		/* CollectionLoaderClass::Load_W3D (CollectionPrototypeClass, CLASSID_COLLECTION) */
		CollectionDefClass *def = new CollectionDefClass;
		if (def->Load(cload) != WW3D_ERROR_OK) {
			delete def;
			return NULL;
		}
		TestProtoClass *p = new TestProtoClass(def->Get_Name(), 23, NULL);
		delete def;
		return p;
	}
	case K_HLOD: {
		/* HLodLoaderClass::Load_W3D (HLodPrototypeClass, CLASSID_HLOD) */
		HLodDefClass *def = new HLodDefClass;
		if (def->Load_W3D(cload) != WW3D_ERROR_OK) {
			delete def;
			return NULL;
		}
		TestProtoClass *p = new TestProtoClass(def->Get_Name(), 25, NULL);
		delete def;
		return p;
	}
	case K_AGGREGATE: {
		/* AggregateLoaderClass::Load_W3D (AggregatePrototypeClass: the
		** definition's name and Class_ID) */
		AggregateDefClass *def = new AggregateDefClass;
		if (def->Load_W3D(cload) != WW3D_ERROR_OK) {
			delete def;
			return NULL;
		}
		TestProtoClass *p = new TestProtoClass(def->Get_Name(), def->Class_ID(), NULL);
		delete def;
		return p;
	}
	case K_NULL: {
		/* NullLoaderClass::Load_W3D */
		W3dNullObjectStruct null;
		cload.Read(&null, sizeof(null));
		return new NullPrototypeClass(null);
	}
	case K_DAZZLE: {
		/* DazzleLoaderClass::Load_W3D, DazzlePrototypeClass::Load_W3D */
		StringClass Name;
		StringClass dazzle_type;
		while (cload.Open_Chunk()) {
			switch (cload.Cur_Chunk_ID()) {
				READ_WWSTRING_CHUNK(cload, W3D_CHUNK_DAZZLE_NAME, Name);
				READ_WWSTRING_CHUNK(cload, W3D_CHUNK_DAZZLE_TYPENAME, dazzle_type);
			default:
				break;
			}
			cload.Close_Chunk();
		}
		return new TestProtoClass((const char *)Name, 31, NULL);
	}
	case K_BOX:
	case K_SPHERE:
	case K_RING: {
		/* the real loaders; wrapped for Create */
		PrototypeClass *inner = Kind == K_BOX ? g_box_loader.Load_W3D(cload)
			: Kind == K_SPHERE ? g_sphere_loader.Load_W3D(cload) : g_ring_loader.Load_W3D(cload);
		if (!inner) return NULL;
		return new TestProtoClass(inner->Get_Name(), inner->Get_Class_ID(), inner);
	}
	default:
		abort(); /* not translated: not given to the C++ */
	}
}

