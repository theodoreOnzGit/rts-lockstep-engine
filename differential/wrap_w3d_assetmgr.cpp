std::string normalise(const char *path)
{
	if (path[0] == '\\' || path[0] == '/') ++path;
	std::string s;
	for (; *path; ++path) {
		char c = *path;
		if (c == '/') c = '\\';
		if (c >= 'A' && c <= 'Z') c += 'a' - 'A';
		s += c;
	}
	return s;
}
bool doesFileExist(const char *path) { return g_files.count(normalise(path)) != 0; }

enum GameFileType { FILE_TYPE_COMPLETELY_UNKNOWN = 0, FILE_TYPE_W3D, FILE_TYPE_TGA, FILE_TYPE_DDS };
inline bool isImageFileType(GameFileType fileType) { return (fileType == FILE_TYPE_TGA || fileType == FILE_TYPE_DDS); }

class TestGameFile : public FileClass
{
public:
	TestGameFile(char const *filename) : m_fileExists(false), m_theFile(NULL)
	{
		m_filePath[0] = 0;
		m_filename[0] = 0;
		if (filename) Set_Name(filename);
	}
	~TestGameFile() { Close(); }
	virtual char const *File_Name(void) const { return m_filename; }
	/* GameFileClass::Set_Name (W3DFileSystem.cpp), the same steps */
	virtual char const *Set_Name(char const *filename)
	{
		if (Is_Open()) Close();
		strncpy(m_filename, filename, _MAX_PATH_);
		char name[_MAX_PATH_];
		const int EXT_LEN = 32;
		char extension[EXT_LEN];
		extension[0] = 0;
		strcpy(name, filename);
		int i = strlen(name);
		i--;
		int extLen = 1;
		while (i > 0 && extLen < EXT_LEN) {
			if (name[i] == '.') {
				strcpy(extension, name + i);
				name[i] = 0;
				break;
			}
			i--;
			extLen++;
		}
		GameFileType fileType = FILE_TYPE_COMPLETELY_UNKNOWN;
		if (stricmp(extension, ".w3d") == 0) fileType = FILE_TYPE_W3D;
		else if (stricmp(extension, ".tga") == 0) fileType = FILE_TYPE_TGA;
		else if (stricmp(extension, ".dds") == 0) fileType = FILE_TYPE_DDS;
		if (fileType == FILE_TYPE_W3D) {
			sprintf(m_filePath, "Data/%s/Art/W3D/", g_language.c_str());
			strcat(m_filePath, filename);
		}
		if (isImageFileType(fileType)) {
			sprintf(m_filePath, "Data/%s/Art/Textures/", g_language.c_str());
			strcat(m_filePath, filename);
		}
		m_fileExists = doesFileExist(m_filePath);
		if (!m_fileExists) {
			if (fileType == FILE_TYPE_W3D) {
				strcpy(m_filePath, "Art/W3D/");
				strcat(m_filePath, filename);
			} else if (isImageFileType(fileType)) {
				strcpy(m_filePath, "Art/Textures/");
				strcat(m_filePath, filename);
			} else
				strcpy(m_filePath, filename);
			m_fileExists = doesFileExist(m_filePath);
		}
		/* LOAD_TEST_ASSETS */
		if (!m_fileExists) {
			if (fileType == FILE_TYPE_W3D) {
				strcpy(m_filePath, "../TestArt/");
				strcat(m_filePath, filename);
			} else if (isImageFileType(fileType)) {
				strcpy(m_filePath, "../TestArt/");
				strcat(m_filePath, filename);
			}
			m_fileExists = doesFileExist(m_filePath);
		}
		if (!m_fileExists && g_has_global_data) {
			if (fileType == FILE_TYPE_W3D) {
				sprintf(m_filePath, "%sW3D/", g_user_data.c_str());
				strcat(m_filePath, filename);
			}
			if (isImageFileType(fileType)) {
				sprintf(m_filePath, "%sTextures/", g_user_data.c_str());
				strcat(m_filePath, filename);
			}
			m_fileExists = doesFileExist(m_filePath);
		}
		if (!m_fileExists && g_has_global_data) {
			if (fileType == FILE_TYPE_TGA) {
				sprintf(m_filePath, "%sMapPreviews/", g_user_data.c_str());
				strcat(m_filePath, filename);
			}
			m_fileExists = doesFileExist(m_filePath);
		}
		return m_filename;
	}
	virtual int Create(void) { abort(); }
	virtual int Delete(void) { abort(); }
	virtual bool Is_Available(int = false) { return m_fileExists; }
	virtual bool Is_Open(void) const { return m_theFile != NULL; }
	virtual int Open(char const *filename, int rights = READ)
	{
		Set_Name(filename);
		if (Is_Available(false)) return Open(rights);
		return false;
	}
	virtual int Open(int rights = READ)
	{
		if (rights != READ) return false;
		std::map<std::string, std::string>::iterator it = g_files.find(normalise(m_filePath));
		if (it == g_files.end()) return false;
		m_theFile = ref_w3d_ramfile_open(it->second.data(), (int)it->second.size());
		return m_theFile != NULL;
	}
	virtual int Read(void *buffer, int len) { return m_theFile ? ref_w3d_ramfile_read(m_theFile, buffer, len) : 0; }
	virtual int Seek(int pos, int dir = SEEK_CUR)
	{
		int mode = 1;
		switch (dir) {
		default:
		case SEEK_CUR: mode = 1; break;
		case SEEK_SET: mode = 0; break;
		case SEEK_END: mode = 2; break;
		}
		if (m_theFile) return ref_w3d_ramfile_seek(m_theFile, pos, mode);
		return 0xFFFFFFFF;
	}
	virtual int Size(void) { return m_theFile ? ref_w3d_ramfile_size(m_theFile) : 0xFFFFFFFF; }
	virtual int Write(void const *, int) { return 0; }
	virtual void Close(void)
	{
		if (m_theFile) {
			ref_w3d_ramfile_close(m_theFile);
			m_theFile = NULL;
		}
	}
private:
	enum { _MAX_PATH_ = 260 };
	bool m_fileExists;
	void *m_theFile;
	char m_filePath[_MAX_PATH_];
	char m_filename[_MAX_PATH_];
};

