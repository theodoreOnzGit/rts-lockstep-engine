extern "C" {

/* every instance of the chain is gone: TheWritableGlobalData == NULL and
** the next NEW GlobalData is the original (m_theOriginal == NULL) */
void ref_globaldata_clear(void)
{
	if (TheWritableGlobalData) {
		TheWritableGlobalData->reset();
		delete TheWritableGlobalData;
	}
	TheWritableGlobalData = 0;
	GlobalData::m_theOriginal = 0;
}

/* TheWritableGlobalData = NEW GlobalData, if there is none (what the engine
** does before it reads GameData) */
void ref_globaldata_create(void)
{
	if (!TheWritableGlobalData) TheWritableGlobalData = new (ShimZeroFill{}) GlobalData; /* NEW GlobalData */
}

/* TheWritableGlobalData->reset() */
void ref_globaldata_reset(void)
{
	if (TheWritableGlobalData) TheWritableGlobalData->reset();
}

/* how many instances the m_next chain links, from TheWritableGlobalData */
int ref_globaldata_len(void)
{
	int n = 0;
	for (const GlobalData *g = TheWritableGlobalData; g; g = g->m_next) ++n;
	return n;
}

/* the chain, newest first: the count (u32), then each instance's members.
** Returns the length (may exceed cap). */
int ref_globaldata_dump(unsigned char *buf, int cap)
{
	g_dump.clear();
	putU32((unsigned)ref_globaldata_len());
	for (const GlobalData *g = TheWritableGlobalData; g; g = g->m_next) dumpOne(*g);
	return finish(buf, cap);
}

/* the number of entries of the GameData table (without the terminator), and
** the token of the i-th */
int ref_globaldata_field_count(void)
{
	int n = 0;
	while (GlobalData::s_GlobalDataFieldParseTable[n].token) ++n;
	return n;
}
const char *ref_globaldata_field_token(int i) { return GlobalData::s_GlobalDataFieldParseTable[i].token; }

/* setTimeOfDay on TheWritableGlobalData; returns its Bool */
int ref_globaldata_set_time_of_day(int tod)
{
	return TheWritableGlobalData->setTimeOfDay((TimeOfDay)tod) ? 1 : 0;
}

/* TheWritableGlobalData->m_weaponBonusSet->appendBonuses(flags, bonus) on a
** fresh WeaponBonus: its five fields (bits) */
void ref_globaldata_append_bonuses(unsigned flags, unsigned *out)
{
	WeaponBonus bonus;
	TheWritableGlobalData->m_weaponBonusSet->appendBonuses(flags, bonus);
	for (int f = 0; f < WeaponBonus::FIELD_COUNT; ++f) {
		Real r = bonus.getField((WeaponBonus::Field)f);
		memcpy(&out[f], &r, 4);
	}
}

/* INI::load(filename, loadType, xfer ? &crc : NULL) of a registered file (the
** files of ref_ini_add_file). Returns the throw status (see
** unnamedEnumStatus), with the XferCRC's getCRC() and the exception message
** or code. The chain is not reset. */
int ref_globaldata_load(const char *filename, int load_type, int with_xfer, unsigned *crc, char *msg, int msgCap, unsigned *code)
{
	XferCRC x;
	int status = 0;
	try {
		INI ini;
		ini.load(AsciiString(filename), (INILoadType)load_type, with_xfer ? &x : NULL);
	}
	catch (INIException &e) {
		status = 1;
		const char *m = e.mFailureMessage ? e.mFailureMessage : "";
		int n = (int)strlen(m);
		*code = (unsigned)n;
		if (n + 1 <= msgCap) memcpy(msg, m, n + 1);
	}
	catch (ErrorCode c) { status = 3; *code = (unsigned)c; }
	catch (std::out_of_range &) { status = 4; }
	catch (...) { status = unnamedEnumStatus(code); }
	*crc = x.getCRC();
	return status;
}

} /* extern "C" */
