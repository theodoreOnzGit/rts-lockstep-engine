/* ---- the logic height map and the render object that reads it (WorldHeightMap.h,
** BaseHeightMap.h); see wrap_terrain_logic.cpp */
class WorldHeightMap
{
public:
	Int m_width, m_height, m_borderSize, m_dataSize;
	std::vector<UnsignedByte> m_data;
	std::vector<ICoord2D> m_boundaries;
	Int getXExtent(void) {return m_width;}
	Int getYExtent(void) {return m_height;}
	Int getBorderSizeInline(void) const { return m_borderSize; }
	const UnsignedByte *getDataPtr(void) const { return m_data.empty() ? 0 : &m_data[0]; }
	UnsignedByte getHeight(Int xIndex, Int yIndex)
	{
		Int ndx = (yIndex*m_width)+xIndex;
		if ((ndx>=0) && (ndx<m_dataSize) && !m_data.empty())
			return(m_data[ndx]);
		else
			return(0);
	}
	void setRawHeight(Int xIndex, Int yIndex, UnsignedByte height) {
		Int ndx = (yIndex*m_width)+xIndex;
		if ((ndx>=0) && (ndx<m_dataSize) && !m_data.empty()) m_data[ndx]=height;
	}
};
