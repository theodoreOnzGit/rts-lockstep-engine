/* GeometryInfo (Geometry.h): the accessors TerrainLogic.cpp calls over the plain fields, and `set`,
** which is Geometry.cpp's own (extracted verbatim by build.rs: a sphere and a cylinder have their minor
** radius set to the major). The enum GeometryType is the real one (terrain_logic_gen_defs.h). The bounding
** radii, which TerrainLogic.cpp does not read, are not kept. */
class TLGeometryInfo
{
public:
	GeometryType m_type;
	Bool m_isSmall;
	Real m_height, m_majorRadius, m_minorRadius;
	void calcBoundingStuff() {}
	void set(GeometryType type, Bool isSmall, Real height, Real majorRadius, Real minorRadius);
	TLGeometryInfo(GeometryType type = GEOMETRY_SPHERE, Bool isSmall = false, Real height = 1.0f, Real majorRadius = 1.0f, Real minorRadius = 1.0f)
	{
		set(type, isSmall, height, majorRadius, minorRadius);
	}
	GeometryType getGeomType() const { return m_type; }
	Bool getIsSmall() const { return m_isSmall; }
	Real getMajorRadius() const { return m_majorRadius; }
	Real getMinorRadius() const { return m_minorRadius; }
};

