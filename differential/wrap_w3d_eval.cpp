/* The same file as wrap_w3d.cpp: GameFileClass's Read and Seek over RAMFile. */
class TestFile : public FileClass
{
public:
	TestFile(const char *data, int len) : m_theFile(ref_w3d_ramfile_open(data, len)) {}
	~TestFile() { ref_w3d_ramfile_close(m_theFile); }
	virtual char const *File_Name(void) const { return "test.w3d"; }
	virtual char const *Set_Name(char const *) { return "test.w3d"; }
	virtual int Create(void) { abort(); }
	virtual int Delete(void) { abort(); }
	virtual bool Is_Available(int = false) { return true; }
	virtual bool Is_Open(void) const { return true; }
	virtual int Open(char const *, int = READ) { return 1; }
	virtual int Open(int = READ) { return 1; }
	virtual int Read(void *buffer, int len) { return ref_w3d_ramfile_read(m_theFile, buffer, len); }
	virtual int Seek(int pos, int dir = SEEK_CUR)
	{
		int mode = 1;
		switch (dir) {
		default:
		case SEEK_CUR: mode = 1; break;
		case SEEK_SET: mode = 0; break;
		case SEEK_END: mode = 2; break;
		}
		return ref_w3d_ramfile_seek(m_theFile, pos, mode);
	}
	virtual int Size(void) { return ref_w3d_ramfile_size(m_theFile); }
	virtual int Write(void const *, int) { abort(); }
	virtual void Close(void) {}
private:
	void *m_theFile;
};

std::vector<unsigned char> g_log;
void put(const void *p, size_t n) { g_log.insert(g_log.end(), (const unsigned char *)p, (const unsigned char *)p + n); }
void put8(int v) { g_log.push_back((unsigned char)v); }
void put32(uint32_t v) { put(&v, 4); }
void putF(float f) { put(&f, 4); }
void putM(const Matrix3D &m)
{
	for (int r = 0; r < 3; ++r)
		for (int c = 0; c < 4; ++c) putF(m[r][c]);
}

std::vector<HTreeClass *> g_trees;
/* every animation loaded, in load order; kind 0 raw, 1 compressed, 2 morph */
std::vector<std::pair<HAnimClass *, int> > g_anims;

HTreeClass *find_tree(const char *name)
{
	for (size_t i = 0; i < g_trees.size(); ++i)
		if (memcmp(g_trees[i]->Get_Name(), name, W3D_NAME_LEN) == 0) return g_trees[i];
	return NULL;
}

HAnimClass *find_pose(const char *name)
{
	for (size_t i = 0; i < g_anims.size(); ++i) {
		if (g_anims[i].second == 2) continue;
		if (strcmp(g_anims[i].first->Get_Name(), name) == 0) {
			g_anims[i].first->Add_Ref();
			return g_anims[i].first;
		}
	}
	return NULL;
}

/* The sentinel a Get_Orientation or Get_Transform that leaves its output
** alone shows. */
const uint32_t SENTINEL = 0x7FC0DEADu;
float sentinel()
{
	float f;
	memcpy(&f, &SENTINEL, 4);
	return f;
}

struct Reader {
	const unsigned char *p;
	int n, i;
	uint32_t u() { uint32_t v; memcpy(&v, p + i, 4); i += 4; return v; }
	float f() { float v; memcpy(&v, p + i, 4); i += 4; return v; }
	Matrix3D m()
	{
		float a[12];
		for (int k = 0; k < 12; ++k) a[k] = f();
		return Matrix3D(a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], a[9], a[10], a[11]);
	}
};

void log_tree(HTreeClass *t)
{
	for (int p = 0; p < t->Num_Pivots(); ++p) {
		putM(t->Get_Transform(p));
		put8(t->Get_Visibility(p) ? 1 : 0);
	}
}

void free_all()
{
	for (size_t i = g_anims.size(); i-- > 0;) g_anims[i].first->Release_Ref();
	g_anims.clear();
	for (size_t i = 0; i < g_trees.size(); ++i) delete g_trees[i];
	g_trees.clear();
}

