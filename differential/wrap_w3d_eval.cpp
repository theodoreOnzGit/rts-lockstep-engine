/* Differential-test wrapper for the W3D animation evaluation (upstream commit
** 0a05454d), GitHub issue #10, step 3:
**   WW3D2/motchan.cpp     Get_Vector, Get_QuatVector, the time-code search,
**                         the adaptive-delta decompression, Get_Bit
**   WW3D2/hrawanim.cpp    HRawAnimClass::Get_Translation/Orientation/
**                         Transform/Visibility
**   WW3D2/hcanim.cpp      HCompressedAnimClass::Get_* (the same)
**   WW3D2/hmorphanim.cpp  HMorphAnimClass::Get_Translation/Orientation/
**                         Transform and TimeCodedMorphKeysClass::
**                         Get_Morph_Info, get_index, binary_search_index
**   WW3D2/htree.cpp       Base_Update, both Anim_Update, Blend_Update, both
**                         Simple_Evaluate_Pivot, Capture_Bone, Release_Bone,
**                         Control_Bone; pivot.cpp Capture_Update
**   WWMath/quat.cpp       Fast_Slerp
**   WW3D2/hanim.cpp       (#162) HAnimComboClass, HAnimComboDataClass,
**                         PivotMapClass, NamedPivotMapClass; htree.cpp's
**                         Combo_Update over them
** all COMPILED from upstream's files: motchan.cpp, htree.cpp, hrawanim.cpp,
** hcanim.cpp, pivot.cpp and quat.cpp in the upstream_w3d library
** (wrap_w3d.cpp, with its MSVC-scope edits, see build.rs; htree.cpp's and
** hrawanim.cpp's Float_To_Long calls go through wrap_w3d.cpp's
** Ref_W3D_Float_To_Long, either branch, #19), the morph
** functions as verbatim segments of hmorphanim.cpp in upstream_w3d_morph
** (morph_def.cpp, see build.rs), matrix3d.cpp and the WWMath tables in
** upstream_wwmath. This file only drives them; nothing of the evaluation is
** transcribed.
**
** The file: one W3D file whose top-level chunks are loaded in order by the
** real loaders (hierarchies, raw, compressed and morph animations; anything
** else skipped). The hierarchy an animation names is found among the
** hierarchies loaded before it (16 bytes compared, as wrap_w3d.cpp's
** stand-in; through its g_w3d_htree_hook), and a morph channel's pose among
** the raw and compressed animations loaded before it (by Get_Name(), with
** strcmp; through wrap_w3d_morph.cpp's g_w3d_hanim_hook, adding the
** reference the real Get_HAnim adds).
**
** Then a script of evaluations (see ref_w3d_eval), each result appended to a
** byte log that tests/differential_w3d.rs (section 13) reproduces from the
** Rust. Allocation (zero-filled) and the file are wrap_w3d.cpp's. */
