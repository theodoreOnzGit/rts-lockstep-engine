/* Load the file's top-level chunks (see above), logging 'L', for each chunk
** its kind (0 hierarchy, 1 raw, 2 compressed, 3 morph, 9 skipped) and the
** loader's result; then the script. Each op is a byte and uint32 operands
** (indices, pivots as int, frames and matrices as float bits, matrices as 12
** floats row-major):
**   1 T anim pivot frame       Get_Translation         -> 3 floats
**   2 Q anim pivot frame       Get_Orientation         -> 4 floats
**   3 M anim pivot frame       Get_Transform           -> 12 floats
**   4 V anim pivot frame       Get_Visibility          -> 1 byte
**   5 A tree anim frame root   Anim_Update(HAnimClass*)      -> the tree
**   6 R tree anim frame root   Anim_Update(HRawAnimClass*)   -> the tree
**   7 B tree a0 f0 a1 f1 pct root  Blend_Update            -> the tree
**   8 U tree root              Base_Update             -> the tree
**   9 S tree anim pivot frame obj  Simple_Evaluate_Pivot(motion, ...)
**                              -> 1 byte, 12 floats
**  10 s tree pivot obj         Simple_Evaluate_Pivot(pivot, ...)
**                              -> 1 byte, 12 floats
**  11 C tree bone capture wst matrix  Capture_Bone + Control_Bone, or
**                              Release_Bone when capture is 0 -> nothing
**  (#162) the combos (HAnimComboClass), indices into the ops' own lists:
**  12 combo n                 new HAnimComboClass(n), or () for n = -1
**  13 combo i anim            Set_Motion (anim -1: NULL)
**  14 / 15 / 16 combo i f     Set_Frame / Set_Prev_Frame / Set_Weight
**  17 combo i map             Set_Pivot_Weight_Map (map -1: NULL)
**  18 named                   new PivotMapClass, or NamedPivotMapClass
**  19 map w                   Add(w)
**  20 map name w              NamedPivotMapClass::Add(COMBO_NAMES[name], w)
**                             (nothing on a plain map)
**  21 map tree                Update_Pivot_Map(tree) (nothing on a plain map)
**  22 combo i                 Peek_Anim_Combo_Data(i)->Build_Active_Pivot_Map
**  23 combo                   Normalize_Weights -> 1 byte, the combo
**  24 tree combo root         Combo_Update            -> the tree
**  25                         new HAnimComboDataClass(true)
**  26 / 27 combo data         Append_ / Remove_Anim_Combo_Data
**  28 / 29 combo              Clear / Reset
**  30 combo                   -> the combo
**  31 map                     -> the map
** "The combo" is Get_Num_Anims, then per entry its frame, previous frame and
** weight, its animation's index (0xFFFFFFFF: none) and its map's Count() and
** elements (0xFFFFFFFF: none). "The tree" is every pivot's Get_Transform (12 floats) and Get_Visibility
** (1 byte). Orientation and transform outputs start as a NaN sentinel
** (0x7FC0DEAD), which shows when the function leaves them alone. The Rust
** test only sends ops that are defined upstream. */
int ref_w3d_eval(const char *data, int len, const unsigned char *script, int slen, unsigned char *log, int cap,
	int *log_len)
{
	g_log.clear();
	ref_wwmath_init_tables();
	{
		TestFile file(data, len);
		ChunkLoadClass cload(&file);
		g_w3d_htree_hook = find_tree;
		g_w3d_hanim_hook = find_pose;
		put8('L');
		while (cload.Open_Chunk()) {
			switch (cload.Cur_Chunk_ID()) {
			case W3D_CHUNK_HIERARCHY: {
				HTreeClass *t = new HTreeClass;
				int r = t->Load_W3D(cload);
				put8(0); put8(r);
				if (r == HTreeClass::OK) g_trees.push_back(t); else delete t;
				break;
			}
			case W3D_CHUNK_ANIMATION: {
				HRawAnimClass *a = new HRawAnimClass;
				int r = a->Load_W3D(cload);
				put8(1); put8(r);
				if (r == HRawAnimClass::OK) g_anims.push_back(std::make_pair((HAnimClass *)a, 0)); else a->Release_Ref();
				break;
			}
			case W3D_CHUNK_COMPRESSED_ANIMATION: {
				HCompressedAnimClass *a = new HCompressedAnimClass;
				int r = a->Load_W3D(cload);
				put8(2); put8(r);
				if (r == HCompressedAnimClass::OK) g_anims.push_back(std::make_pair((HAnimClass *)a, 1)); else a->Release_Ref();
				break;
			}
			case W3D_CHUNK_MORPH_ANIMATION: {
				HMorphAnimClass *a = new HMorphAnimClass;
				int r = a->Load_W3D(cload);
				put8(3); put8(r);
				if (r == HMorphAnimClass::OK) g_anims.push_back(std::make_pair((HAnimClass *)a, 2)); else a->Release_Ref();
				break;
			}
			default:
				put8(9); put8(0);
				break;
			}
			cload.Close_Chunk();
		}
		g_w3d_htree_hook = NULL;
		g_w3d_hanim_hook = NULL;
	}
	put32((uint32_t)g_trees.size());
	put32((uint32_t)g_anims.size());

	Reader rd = { script, slen, 0 };
	while (rd.i < rd.n) {
		int op = script[rd.i++];
		put8(op);
		switch (op) {
		case 1: case 2: case 3: case 4: {
			HAnimClass *a = g_anims[rd.u()].first;
			int pivot = (int)rd.u();
			float frame = rd.f();
			if (op == 1) {
				Vector3 t(sentinel(), sentinel(), sentinel());
				a->Get_Translation(t, pivot, frame);
				putF(t.X); putF(t.Y); putF(t.Z);
			} else if (op == 2) {
				Quaternion q(sentinel(), sentinel(), sentinel(), sentinel());
				a->Get_Orientation(q, pivot, frame);
				putF(q.X); putF(q.Y); putF(q.Z); putF(q.W);
			} else if (op == 3) {
				float s = sentinel();
				Matrix3D m(s, s, s, s, s, s, s, s, s, s, s, s);
				a->Get_Transform(m, pivot, frame);
				putM(m);
			} else {
				put8(a->Get_Visibility(pivot, frame) ? 1 : 0);
			}
			break;
		}
		case 5: case 6: {
			HTreeClass *t = g_trees[rd.u()];
			HAnimClass *a = g_anims[rd.u()].first;
			float frame = rd.f();
			Matrix3D root = rd.m();
			if (op == 5) t->Anim_Update(root, a, frame);
			else t->Anim_Update(root, (HRawAnimClass *)a, frame);
			log_tree(t);
			break;
		}
		case 7: {
			HTreeClass *t = g_trees[rd.u()];
			HAnimClass *a0 = g_anims[rd.u()].first;
			float f0 = rd.f();
			HAnimClass *a1 = g_anims[rd.u()].first;
			float f1 = rd.f();
			float pct = rd.f();
			Matrix3D root = rd.m();
			t->Blend_Update(root, a0, f0, a1, f1, pct);
			log_tree(t);
			break;
		}
		case 8: {
			HTreeClass *t = g_trees[rd.u()];
			Matrix3D root = rd.m();
			t->Base_Update(root);
			log_tree(t);
			break;
		}
		case 9: {
			HTreeClass *t = g_trees[rd.u()];
			HAnimClass *a = g_anims[rd.u()].first;
			int pivot = (int)rd.u();
			float frame = rd.f();
			Matrix3D obj = rd.m();
			Matrix3D end;
			bool ok = t->Simple_Evaluate_Pivot(a, pivot, frame, obj, &end);
			put8(ok ? 1 : 0);
			putM(end);
			break;
		}
		case 10: {
			HTreeClass *t = g_trees[rd.u()];
			int pivot = (int)rd.u();
			Matrix3D obj = rd.m();
			Matrix3D end;
			bool ok = t->Simple_Evaluate_Pivot(pivot, obj, &end);
			put8(ok ? 1 : 0);
			putM(end);
			break;
		}
		case 11: {
			HTreeClass *t = g_trees[rd.u()];
			int bone = (int)rd.u();
			uint32_t capture = rd.u();
			uint32_t wst = rd.u();
			Matrix3D m = rd.m();
			if (capture) {
				t->Capture_Bone(bone);
				t->Control_Bone(bone, m, wst != 0);
			} else {
				t->Release_Bone(bone);
			}
			break;
		}
		case 12: {
			int n = (int)rd.u();
			g_combos.push_back(n < 0 ? new HAnimComboClass() : new HAnimComboClass(n));
			break;
		}
		case 13: case 14: case 15: case 16: case 17: {
			HAnimComboClass *c = g_combos[rd.u()];
			int i = (int)rd.u();
			uint32_t v = rd.u();
			float f;
			memcpy(&f, &v, 4);
			if (op == 13) c->Set_Motion(i, (int)v < 0 ? NULL : g_anims[v].first);
			else if (op == 14) c->Set_Frame(i, f);
			else if (op == 15) c->Set_Prev_Frame(i, f);
			else if (op == 16) c->Set_Weight(i, f);
			else c->Set_Pivot_Weight_Map(i, (int)v < 0 ? NULL : g_maps[v]);
			break;
		}
		case 18: {
			uint32_t named = rd.u();
			g_maps.push_back(named ? (PivotMapClass *)new NamedPivotMapClass : new PivotMapClass);
			break;
		}
		case 19: {
			PivotMapClass *m = g_maps[rd.u()];
			float w = rd.f();
			m->Add(w);
			break;
		}
		case 20: {
			PivotMapClass *m = g_maps[rd.u()];
			uint32_t name = rd.u();
			float w = rd.f();
			if (NamedPivotMapClass *n = m->As_Named_Pivot_Map()) n->Add(COMBO_NAMES[name], w);
			break;
		}
		case 21: {
			PivotMapClass *m = g_maps[rd.u()];
			HTreeClass *t = g_trees[rd.u()];
			if (NamedPivotMapClass *n = m->As_Named_Pivot_Map()) n->Update_Pivot_Map(t);
			break;
		}
		case 22: {
			HAnimComboClass *c = g_combos[rd.u()];
			int i = (int)rd.u();
			c->Peek_Anim_Combo_Data(i)->Build_Active_Pivot_Map();
			break;
		}
		case 23: {
			HAnimComboClass *c = g_combos[rd.u()];
			put8(c->Normalize_Weights() ? 1 : 0);
			put_combo(c);
			break;
		}
		case 24: {
			HTreeClass *t = g_trees[rd.u()];
			HAnimComboClass *c = g_combos[rd.u()];
			Matrix3D root = rd.m();
			t->Combo_Update(root, c);
			log_tree(t);
			break;
		}
		case 25:
			g_datas.push_back(new HAnimComboDataClass(true));
			break;
		case 26: case 27: {
			HAnimComboClass *c = g_combos[rd.u()];
			HAnimComboDataClass *d = g_datas[rd.u()];
			if (op == 26) c->Append_Anim_Combo_Data(d); else c->Remove_Anim_Combo_Data(d);
			break;
		}
		case 28: case 29: case 30: {
			HAnimComboClass *c = g_combos[rd.u()];
			if (op == 28) c->Clear(); else if (op == 29) c->Reset(); else put_combo(c);
			break;
		}
		case 31:
			put_map(g_maps[rd.u()]);
			break;
		default:
			abort();
		}
	}
	free_all();
	forget_pool_blocks();
	int n = (int)g_log.size();
	*log_len = n;
	if (n > cap) n = cap;
	if (n > 0) memcpy(log, &g_log[0], n);
	return 0;
}

