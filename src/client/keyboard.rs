//! GitHub #131: the keyboard's printable key names (`Keyboard::m_keyNames`), which `HotKeyTranslator` reads to turn a
//! key into the letter a control bar button's hot key names ([`crate::client::hot_key`]).
//!
//! # As upstream reads it
//!
//! `Keyboard::init` calls `initKeyNames`: every one of the 256 keys gets no name (`L'\0'` plain, shifted and with the
//! second shift); the keys every layout shares are named (the arrows and the function keys with none, the keypad's
//! digits, backspace, delete, tab, enter, space); then the layout's own: `OurLanguage` (the game's language), or French
//! when the Windows keyboard layout's low word is one of the five French ones (`GetKeyboardLayout(0)`). US, Japanese,
//! Korean, Jabber, unknown and Spanish share the US table; UK, German, French and Italian have their own, and set the
//! second-shift key to right Alt. `getPrintableKey(key, state)` answers the name: plain (0), shifted (1), second shift
//! (2); `L'\0'` for a state outside 0..3 (the key, an `UnsignedByte`, is always inside the table).
//!
//! # Upstream quirks that are kept
//!
//! - The tables are the source's, entry by entry and in order (generated from `Keyboard.cpp`'s `_set_keyname_` calls:
//!   316 of them); a later entry for a key replaces an earlier one (`KEY_DEL`'s delete is a backspace).
//! - `Keyboard.cpp` is a Windows-1252 file: its one non-ASCII character literal (the UK table's `KEY_4` with the second
//!   shift, byte 0x80) is the euro sign, U+20AC, as MSVC reads it (not U+0080).
//!
//! # Where this differs from upstream
//!
//! - The keyboard layout is not the operating system's: the caller gives the layout id (the client gives US English,
//!   `0x0409`; the browser does not say).
//!
//! # Representation
//!
//! [`KeyNames`] is `m_keyNames` with `m_shift2Key`.

