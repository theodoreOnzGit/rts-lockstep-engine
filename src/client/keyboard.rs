/// `m_keyNames` (and `m_shift2Key`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KeyNames {
    /// Per key: `stdKey`, `shifted`, `shifted2`.
    pub names: [[u16; 3]; KEY_NAMES_COUNT],
    /// `m_shift2Key`.
    pub shift2_key: u8,
}

impl Default for KeyNames {
    fn default() -> Self {
        KeyNames { names: [[0; 3]; KEY_NAMES_COUNT], shift2_key: KEY_NONE }
    }
}

impl KeyNames {
    /// `Keyboard::initKeyNames()` for `language` (`OurLanguage`) and the keyboard layout `layout`
    /// (`GetKeyboardLayout(0)`).
    pub fn init_key_names(language: i32, layout: u32) -> Self {
        let mut k = KeyNames::default();
        let set = |k: &mut KeyNames, rows: &[(u16, u16, u16, u8)]| {
            for &(s, sh, sh2, key) in rows {
                k.names[usize::from(key)] = [s, sh, sh2];
            }
        };
        // "generic to all languages"
        set(&mut k, GENERIC);
        let low = layout & 0xFFFF;
        let mut current = language;
        if low == 0x040c || low == 0x080c || low == 0x0c0c || low == 0x100c || low == 0x140c {
            current = language_id::FRENCH;
        }
        if crate::logic::modules::plant(9189) {
            current = language;
        }
        match current {
            language_id::US | language_id::JAPANESE | language_id::KOREAN | language_id::JABBER | language_id::UNKNOWN | language_id::SPANISH => {
                set(&mut k, US_JAPANESE_KOREAN_JABBER_UNKNOWN_SPANISH);
            }
            language_id::UK => {
                set(&mut k, UK);
                k.shift2_key = KEY_RALT;
            }
            language_id::GERMAN => {
                set(&mut k, GERMAN);
                k.shift2_key = KEY_RALT;
            }
            language_id::FRENCH => {
                set(&mut k, FRENCH);
                k.shift2_key = KEY_RALT;
            }
            language_id::ITALIAN => {
                set(&mut k, ITALIAN);
                k.shift2_key = KEY_RALT;
            }
            _ => {}
        }
        k
    }

    /// `getPrintableKey(key, state)`: the key's name, plain (0), shifted (1) or with the second shift (2); 0 for a
    /// state outside them.
    pub fn get_printable_key(&self, key: u8, state: i32) -> u16 {
        if !(0..MAX_KEY_STATES).contains(&state) {
            return 0;
        }
        let n = &self.names[usize::from(key)];
        if state == 0 {
            n[0]
        } else if state == 1 {
            n[1]
        } else {
            n[2]
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Predicted before the run: in the US table A is `a` / `A`, 1 is `1` / `!`, F1 has no name, delete is a backspace
    /// (the later entry), a state of 3 gives nothing; a French Windows layout (0x040c) under US English gives the French
    /// table (A is `q`, the second shift on right Alt); the US layout under German keeps the German table.
    #[test]
    fn the_key_names_follow_the_language_and_layout() {
        let us = KeyNames::init_key_names(language_id::US, LAYOUT_US_ENGLISH);
        assert_eq!((us.get_printable_key(0x1E, 0), us.get_printable_key(0x1E, 1)), (u16::from(b'a'), u16::from(b'A')));
        assert_eq!((us.get_printable_key(0x02, 0), us.get_printable_key(0x02, 1)), (u16::from(b'1'), u16::from(b'!')));
        assert_eq!(us.get_printable_key(0x3B, 0), 0);
        assert_eq!(us.get_printable_key(0xD3, 0), 8);
        assert_eq!(us.get_printable_key(0x1E, 3), 0);
        assert_eq!(us.shift2_key, KEY_NONE);
        let fr = KeyNames::init_key_names(language_id::US, 0x040c);
        assert_eq!((fr.get_printable_key(0x1E, 0), fr.shift2_key), (u16::from(b'q'), KEY_RALT));
        let de = KeyNames::init_key_names(language_id::GERMAN, LAYOUT_US_ENGLISH);
        assert_eq!(de.get_printable_key(0x15, 0), u16::from(b'z'));
    }
}
