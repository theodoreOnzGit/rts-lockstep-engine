//! `GlobalData` (`TheGlobalData`): the engine's one bag of settings, read from
//! the `GameData` INI block. About half of it is client state (graphics,
//! audio, camera, UI, network); all of it is kept as plain data, so that the
//! block parses exactly as upstream's does and a later layer can read what it
//! needs. Which members **game logic** reads is marked on each field of
//! [`GlobalData`] (**Read by game logic**) and listed in
//! [`READ_BY_GAME_LOGIC`]: 90 of the 280.
//!
//! # What is here
//!
//! - [`GlobalData`] holds every member of the retail configuration, the
//!   constructor's defaults ([`GlobalData::new`]) and `setTimeOfDay`.
//! - [`GLOBAL_DATA_FIELDS`] holds the 336 entries of
//!   `s_GlobalDataFieldParseTable`, in upstream's order.
//! - [`GlobalDataStore`] holds `TheWritableGlobalData`, `m_theOriginal` and the
//!   `m_next` chain of overrides, with `newOverride` and `reset`.
//! - [`parse_game_data_definition`] is `GlobalData::parseGameDataDefinition`
//!   (reached through `INI::parseGameDataDefinition`), the `GameData` block.
//! - [`WeaponBonusSet`](crate::logic::weapon_bonus::WeaponBonusSet) is the one
//!   piece of `Weapon.h` that the `WeaponBonus =` field needs.
//!
//! The struct, its zero value and the parse table are generated by
//! `scripts/gen_global_data.py` from the upstream header and table (280
//! members, 336 fields: too many to type without slips); the constructor and
//! everything else are written by hand, so that the differential test checks
//! the constructor against upstream's instead of against the script.
//!
//! # The retail configuration
//!
//! Upstream compiles members and table entries out of the shipped game: those
//! under `_DEBUG`/`_INTERNAL` (cameras, visibility and threat-map debugging,
//! the latency and packet-loss knobs, `Wireframe`, `ShroudOn`, `SaveStats`, ...),
//! `DUMP_PERF_STATS`, `ALLOW_SURRENDER` (the prison bounty) and
//! `_ALLOW_DEBUG_CHEATS_IN_RELEASE`. The Rust is the shipped game's: those
//! members do not exist, and a `GameData` file that names one of their
//! fields is an unknown field (`INI_UNKNOWN_TOKEN`), as it is in the shipped
//! game. (The differential build is compiled the same way, with `NDEBUG`.)
//!
//! # `newOverride` copies nothing (upstream finding, kept)
//!
//! `parseGameDataDefinition` with `INI_LOAD_CREATE_OVERRIDES` calls
//! `newOverride()`, whose comment says it will "create a new override, copy
//! data from previous override, and return it". Its copy is
//! `*override = *TheWritableGlobalData;`, and `GlobalData`'s copy assignment
//! is declared `private` as
//! `{ DEBUG_CRASH(("unimplemented")); return *this; }`: **in a release build
//! it does nothing**. The new override therefore holds the constructor's
//! defaults, not the previous override's values, plus whatever the override
//! file sets: a map's `GameData` block resets every field it does not name.
//! [`GlobalDataStore::new_override`] does the same (and so does the C++ the
//! differential test runs, which is upstream's code unchanged). This looks
//! like an upstream bug, not a design (the comment says otherwise, and the
//! fields the maps' `GameData` blocks set are few), but it is what the code
//! does. **Awaits the owner:** whether the translation should copy instead.
//!
//! # The chain
//!
//! Upstream links overrides through `m_next` (newest first, the original
//! last), keeps the newest in `TheWritableGlobalData` and the first in the
//! static `m_theOriginal`. Here [`GlobalDataStore`] holds them in a `Vec`:
//! element 0 is `m_theOriginal`, element `i`'s `m_next` is element `i - 1`,
//! and the last is `TheWritableGlobalData`. `reset()` drops every override
//! (newest first) back to the original.
//!
//! # Left out (filesystem, registry, devices, version)
//!
//! - **The executable CRC** of the constructor: it reads the `.exe`
//!   (`GetModuleFileName`), `Data\Scripts\SkirmishScripts.scb` and
//!   `Data\Scripts\MultiplayerScripts.scb` through `TheFileSystem`, and adds
//!   `TheVersion`'s number (the **version** class is not translated).
//!   [`GlobalData::exe_crc`] is 0, which is also what upstream computes when
//!   it finds none of the files and has no `TheVersion` (the CRC of no
//!   bytes); the engine can set it. `m_iniCRC` is 0 until the engine sets it.
//! - **The user data directory** of the constructor (`SHGetSpecialFolderPath`
//!   for My Documents, the registry value `UserDataLeafName`, and
//!   `CreateDirectory`): [`GlobalData::get_path_user_data`] is empty until
//!   [`GlobalData::set_user_data_dir`] is called.
//! - **`GetDoubleClickTime()`**, the operating system's double-click time:
//!   [`DEFAULT_DOUBLE_CLICK_TIME_MS`] (Windows' 500 ms).
//! - **The user preferences** at the end of `parseGameDataDefinition`
//!   (`OptionPreferences`, which reads `Options.ini` from the user data
//!   directory): after every parse upstream overwrites `m_useAlternateMouse`,
//!   `m_clientRetaliationModeEnabled`, `m_doubleClickAttackMove`,
//!   `m_keyboardScrollFactor`, `m_defaultIP`, `m_firewallSendDelay`,
//!   `m_firewallBehavior`, `m_firewallPortAllocationDelta`,
//!   `m_firewallPortOverride`, `m_saveCameraInReplay`, `m_useCameraInReplay`,
//!   `m_displayGamma`, `m_xResolution` and `m_yResolution` from the player's
//!   settings. Here those keep what the INI (or the constructor) gave them;
//!   all are client settings, none read by game logic. The same goes for the
//!   `DEBUG_ASSERTCRASH`/`DEBUG_LOG` lines, which the release build omits.
//!
//! # Upstream quirks that are kept
//!
//! - `DrawSkyBox` is parsed with `parseBool` into a **`Real`**
//!   ([`GlobalData::draw_sky_box`]), and `DebugAI` into the `AIDebugOptions`
//!   enumeration: `parseBool` writes one byte, so the low byte of the value
//!   becomes 0 or 1 and the rest is kept (little endian, as on x86: `yes`
//!   makes the `Real` the subnormal `1.4e-45`, which is non-zero, so it
//!   still reads as true).
//! - `FirewallPortAllocationDelta` is parsed with `parseInt` (four bytes)
//!   into a `Short` (two, followed by two bytes of padding): the member holds
//!   the low 16 bits of the number. `FirewallBehavior`, `FirewallPortOverride`
//!   and the `Network*` fields are `parseInt`s into `UnsignedInt`s: a
//!   negative number is its two's-complement `UnsignedInt`.
//! - `TimeOfDay` in the file sets `m_timeOfDay` only; the ambient, diffuse and
//!   light-position arrays follow it only through `setTimeOfDay`, which the
//!   constructor calls once.
//! - `parseCoord3D` and `parseCoord2D` store each component as it is scanned,
//!   so a line `X:1 Y:oops` throws with `x` already stored. The table entries
//!   read the components themselves for that; [`Ini::parse_coord3d`] returns
//!   the whole value only when every component parses, and does not show this.
//! - `StandardPublicBone` appends to its list (`parseAsciiStringVectorAppend`),
//!   across lines and across blocks.
//! - `HealthBonus_Regular` is commented out upstream ("you cannot set this;
//!   it always has a value of 100%"): that token is unknown.
//!
//! # Where upstream is undefined
//!
//! Nothing new: every undefined input is the INI reader's own (a number out
//! of range, `inf`/`nan`, ...), and returns the same [`Undefined`] error from
//! [`Ini`].
//!
//! [`Undefined`]: crate::common::ini::Undefined
//! [`Ini::parse_coord3d`]: crate::common::ini::Ini::parse_coord3d

