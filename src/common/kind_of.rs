pub struct KindOfNames;
impl BitFlagNames for KindOfNames {
    const NUM_BITS: usize = KINDOF_COUNT as usize;
    const NAMES: &'static [&'static str] = &KIND_OF_NAMES;
}

/// `typedef BitFlags<KINDOF_COUNT> KindOfMaskType`.
pub type KindOfMaskType = BitFlags<KindOfNames>;

/// `KINDOFMASK_NONE`: all clear.
